// Generates registry.json: every library file, what it exports, which other
// library files it needs and which npm packages. An AI (or a person) copying
// one component reads its entry and copies exactly the closure it needs.
//   node scripts/registry.mjs          write registry.json
//   node scripts/registry.mjs --check  fail if registry.json is stale
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';

const root = resolve(dirname(new URL(import.meta.url).pathname), '..');
const ui = join(root, 'ui');
const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const files = walk(ui).filter((f) => /\.(tsx?|css)$/.test(f) && !f.endsWith('index.ts')).sort();

const rel = (f) => relative(root, f).replaceAll('\\', '/');
const resolveImport = (from, spec) => {
  const base = resolve(dirname(from), spec);
  for (const c of [base, `${base}.ts`, `${base}.tsx`, `${base}/index.ts`]) { try { if (statSync(c).isFile()) return c; } catch { /* next */ } }
  return null;
};

const entries = {};
for (const f of files) {
  const src = readFileSync(f, 'utf8');
  const deps = new Set(), pkgs = new Set();
  if (f.endsWith('.css')) {
    for (const m of src.matchAll(/@import\s+"([^"]+)"/g)) if (m[1].startsWith('.')) deps.add(rel(resolve(dirname(f), m[1])));
  } else {
    for (const m of src.matchAll(/(?:import|export)[^'"]*?from\s+['"]([^'"]+)['"]/g)) {
      const s = m[1];
      if (s.startsWith('.')) { const r = resolveImport(f, s); if (r) deps.add(rel(r)); }
      else pkgs.add(s.startsWith('@') ? s.split('/').slice(0, 2).join('/') : s.split('/')[0]);
    }
  }
  const exports = [...src.matchAll(/export\s+(?:function|const|class|type|interface)\s+([A-Za-z0-9_]+)/g)].map((m) => m[1]);
  const doc = src.match(/^\/\*\*([\s\S]*?)\*\//)?.[1].split('\n').map((l) => l.replace(/^\s*\*\s?/, '').trim()).filter(Boolean)[0] ?? '';
  entries[rel(f)] = { summary: doc, exports, files: [...deps].sort(), packages: [...pkgs].filter((p) => p !== 'react').sort() };
}

// Transitive closure: everything to copy for this file.
const closure = (f, seen = new Set()) => { for (const d of entries[f]?.files ?? []) if (!seen.has(d)) { seen.add(d); closure(d, seen); } return seen; };
for (const f of Object.keys(entries)) {
  const all = closure(f);
  entries[f].copy = [f, ...[...all].sort()];
  entries[f].allPackages = [...new Set([...entries[f].packages, ...[...all].flatMap((d) => entries[d]?.packages ?? [])])].sort();
}

const out = JSON.stringify({
  $schema: 'Generated by scripts/registry.mjs — do not edit by hand.',
  styles: 'ui/styles/index.css',
  setup: { packages: ['react', 'react-dom', 'motion', 'lucide-react', 'tailwindcss@4', '@tailwindcss/vite', '@fontsource-variable/dm-sans', '@fontsource/ibm-plex-mono'] },
  files: entries,
}, null, 2) + '\n';

if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(join(root, 'registry.json'), 'utf8'); } catch { /* missing */ }
  if (cur !== out) { console.error('registry.json is stale — run `pnpm registry`.'); process.exit(1); }
  console.log('registry.json is up to date.');
} else {
  writeFileSync(join(root, 'registry.json'), out);
  console.log(`registry.json: ${Object.keys(entries).length} files`);
}
